/**
 * Returns clean generic avatar SVG data URL based on gender or name inference
 */
export function getDefaultAvatarByGender(gender?: string | null, name?: string | null): string {
  const g = gender?.toLowerCase().trim();
  if (g === 'female' || g === 'f' || g === 'woman') {
    return FEMALE_AVATAR_1;
  }
  if (g === 'male' || g === 'm' || g === 'man') {
    return MALE_AVATAR_1;
  }
  if (g === 'non-binary' || g === 'other' || g === 'nb') {
    return NEUTRAL_AVATAR;
  }

  // Infer gender based on name if gender is not explicitly provided
  if (name) {
    const lower = name.toLowerCase();
    const femaleNames = ['dr. sarah', 'sarah', 'dr. elena', 'elena', 'dr. maya', 'maya', 'dr. chloë', 'chloë', 'chloe', 'dr. aisha', 'aisha', 'maria', 'emily', 'jessica', 'lisa', 'anna', 'rachel', 'laura', 'sophia'];
    const maleNames = ['dr. julian', 'julian', 'dr. marcus', 'marcus', 'dr. david', 'david', 'alex', 'john', 'michael', 'james', 'robert', 'william', 'daniel'];
    
    if (femaleNames.some((f) => lower.includes(f))) return FEMALE_AVATAR_1;
    if (maleNames.some((m) => lower.includes(m))) return MALE_AVATAR_1;
  }

  return NEUTRAL_AVATAR;
}

/**
 * Check whether an avatarUrl is valid (non-empty and not broken placeholder)
 */
export function isCustomAvatarUrl(url?: string | null): boolean {
  if (!url || typeof url !== 'string') return false;
  const trimmed = url.trim();
  if (trimmed === '' || trimmed === 'null' || trimmed === 'undefined') return false;
  return true;
}

/**
 * Gets the effective avatar URL with gender fallback
 */
export function getEffectiveAvatarUrl(avatarUrl?: string | null, gender?: string | null, name?: string | null): string {
  if (isCustomAvatarUrl(avatarUrl)) {
    return avatarUrl!.trim();
  }
  return getDefaultAvatarByGender(gender, name);
}
